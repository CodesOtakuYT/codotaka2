const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    // ---------------------------------------------------------------------------------
    // Dependency-free libraries.
    const geom = b.addModule("geom", .{ .root_source_file = b.path("lib/geom.zig"), .target = target, .optimize = optimize });
    const slot_map = b.addModule("slot_map", .{ .root_source_file = b.path("lib/slot_map.zig"), .target = target, .optimize = optimize });
    const drm_sync = b.addModule("drm_sync", .{ .root_source_file = b.path("lib/drm_sync.zig"), .target = target, .optimize = optimize });
    const dmabuf_feedback = b.addModule("dmabuf_feedback", .{ .root_source_file = b.path("lib/dmabuf_feedback.zig"), .target = target, .optimize = optimize });

    // ---------------------------------------------------------------------------------
    // wl: Wayland client layer (libwayland + scanner-generated protocols).
    const wl_c_translate = b.addTranslateC(.{
        .root_source_file = b.path("lib/wl/wl_c.h"),
        .target = target,
        .optimize = optimize,
    });
    const protocols = [_][]const u8{
        "xdg-shell",         "xdg-decoration-unstable-v1",
        "linux-dmabuf-v1",   "linux-drm-syncobj-v1",
        "viewporter",        "fractional-scale-v1",
        "presentation-time", "color-management-v1",
        "cursor-shape-v1",   "tablet-v2",
    };
    var protocol_sources: [protocols.len]std.Build.LazyPath = undefined;
    for (protocols, &protocol_sources) |name, *source| {
        const xml = b.path(b.fmt("protocols/{s}.xml", .{name}));
        const scan_h = b.addSystemCommand(&.{ "wayland-scanner", "client-header" });
        scan_h.addFileArg(xml);
        wl_c_translate.addIncludePath(scan_h.addOutputFileArg(b.fmt("{s}-client-protocol.h", .{name})).dirname());
        const scan_c = b.addSystemCommand(&.{ "wayland-scanner", "private-code" });
        scan_c.addFileArg(xml);
        source.* = scan_c.addOutputFileArg(b.fmt("{s}-protocol.c", .{name}));
    }
    const wl_c = wl_c_translate.createModule();
    const wl = b.addModule("wl", .{
        .root_source_file = b.path("lib/wl/root.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "wl_c", .module = wl_c },
            .{ .name = "geom", .module = geom },
            .{ .name = "dmabuf_feedback", .module = dmabuf_feedback },
        },
    });
    for (protocol_sources) |source| wl.addCSourceFile(.{ .file = source });
    wl.linkSystemLibrary("wayland-client", .{});
    wl_c_translate.linkSystemLibrary("xkbcommon", .{});
    wl.linkSystemLibrary("xkbcommon", .{});

    // ---------------------------------------------------------------------------------
    // Vulkan: bindings generated by vulkan-zig, core infrastructure, presentation.
    const vulkan = b.dependency("vulkan", .{
        .registry = b.dependency("vulkan_headers", .{}).path("registry/vk.xml"),
    }).module("vulkan-zig");

    const vk_core = b.addModule("vk_core", .{
        .root_source_file = b.path("lib/vk_core/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{.{ .name = "vulkan", .module = vulkan }},
    });
    vk_core.linkSystemLibrary("vulkan", .{});

    const frame = b.addModule("frame", .{
        .root_source_file = b.path("lib/frame.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{ .{ .name = "geom", .module = geom }, .{ .name = "wl", .module = wl } },
    });

    const vk_present = b.addModule("vk_present", .{
        .root_source_file = b.path("lib/vk_present/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "vulkan", .module = vulkan },
            .{ .name = "vk_core", .module = vk_core },
            .{ .name = "drm_sync", .module = drm_sync },
            .{ .name = "dmabuf_feedback", .module = dmabuf_feedback },
            .{ .name = "geom", .module = geom },
            .{ .name = "wl", .module = wl },
            .{ .name = "frame", .module = frame },
        },
    });

    // ---------------------------------------------------------------------------------
    // Text: fontconfig + FreeType + HarfBuzz + SheenBidi (built from source) + libunibreak.
    const sheenbidi_dep = b.dependency("sheenbidi", .{});
    const sheenbidi = b.addLibrary(.{
        .name = "SheenBidi",
        .linkage = .static,
        .root_module = b.createModule(.{ .target = target, .optimize = optimize, .link_libc = true }),
    });
    sheenbidi.root_module.addCSourceFile(.{ .file = sheenbidi_dep.path("Source/SheenBidi.c"), .flags = &.{"-std=c11"} });
    sheenbidi.root_module.addCMacro("SB_CONFIG_UNITY", "1");
    sheenbidi.root_module.addIncludePath(sheenbidi_dep.path("Headers"));
    sheenbidi.root_module.addIncludePath(sheenbidi_dep.path("Source"));

    const text_c_translate = b.addTranslateC(.{
        .root_source_file = b.path("lib/text/text_c.h"),
        .target = target,
        .optimize = optimize,
    });
    text_c_translate.addIncludePath(sheenbidi_dep.path("Headers"));
    const text_libs = [_][]const u8{ "freetype2", "harfbuzz", "fontconfig", "libunibreak" };
    for (text_libs) |lib| text_c_translate.linkSystemLibrary(lib, .{});
    const text = b.addModule("text", .{
        .root_source_file = b.path("lib/text/root.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "text_c", .module = text_c_translate.createModule() },
            .{ .name = "frame", .module = frame },
        },
    });
    for (text_libs) |lib| text.linkSystemLibrary(lib, .{});
    text.linkLibrary(sheenbidi);

    // ---------------------------------------------------------------------------------
    // Media: FFmpeg demux + Vulkan Video decode on our VkDevice.
    const av_c_translate = b.addTranslateC(.{
        .root_source_file = b.path("lib/media/av_c.h"),
        .target = target,
        .optimize = optimize,
    });
    const av_libs = [_][]const u8{ "libavformat", "libavcodec", "libavutil", "libswresample" };
    for (av_libs) |lib| av_c_translate.linkSystemLibrary(lib, .{});
    const media = b.addModule("media", .{
        .root_source_file = b.path("lib/media/root.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "av_c", .module = av_c_translate.createModule() },
            .{ .name = "vulkan", .module = vulkan },
            .{ .name = "vk_core", .module = vk_core },
        },
    });
    for (av_libs) |lib| media.linkSystemLibrary(lib, .{});
    // PipeWire playback through a small C shim (SPA's format builders are macro/inline heavy).
    const pw_c_translate = b.addTranslateC(.{
        .root_source_file = b.path("lib/media/pw_c.h"),
        .target = target,
        .optimize = optimize,
    });
    pw_c_translate.addIncludePath(b.path("lib/media"));
    media.addImport("pw_c", pw_c_translate.createModule());
    media.addCSourceFile(.{ .file = b.path("lib/media/pw_shim.c"), .flags = &.{"-std=gnu11"} });
    media.addIncludePath(b.path("lib/media"));
    media.linkSystemLibrary("libpipewire-0.3", .{});

    // ---------------------------------------------------------------------------------
    // Scene graph and client-side decorations.
    const scene = b.addModule("scene", .{
        .root_source_file = b.path("lib/scene/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "wl", .module = wl },
            .{ .name = "geom", .module = geom },
            .{ .name = "frame", .module = frame },
            .{ .name = "slot_map", .module = slot_map },
        },
    });
    const csd = b.addModule("csd", .{
        .root_source_file = b.path("lib/csd/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "wl", .module = wl },
            .{ .name = "frame", .module = frame },
            .{ .name = "scene", .module = scene },
            .{ .name = "text", .module = text },
        },
    });

    // ---------------------------------------------------------------------------------
    // Application.
    const app_imports: []const std.Build.Module.Import = &.{
            .{ .name = "vulkan", .module = vulkan },
            .{ .name = "geom", .module = geom },
            .{ .name = "wl", .module = wl },
            .{ .name = "vk_core", .module = vk_core },
            .{ .name = "vk_present", .module = vk_present },
            .{ .name = "frame", .module = frame },
            .{ .name = "scene", .module = scene },
            .{ .name = "csd", .module = csd },
            .{ .name = "text", .module = text },
            .{ .name = "media", .module = media },
    };
    const exe_mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = app_imports,
    });
    // Offline interpolation quality tool: same renderer, decoder and shaders, no window.
    const eval_mod = b.createModule(.{
        .root_source_file = b.path("src/eval_main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = app_imports,
    });

    const shaders = [_][]const u8{
        "shaders/triangle.vert",
        "shaders/triangle.frag",
        "shaders/text.vert",
        "shaders/text.frag",
        "shaders/video.vert",
        "shaders/video.frag",
        "shaders/rect.vert",
        "shaders/rect.frag",
        "shaders/luma.frag",
        "shaders/splat.comp",
        "shaders/metric.comp",
        "shaders/heat.comp",
        "lib/csd/shaders/decoration.vert",
        "lib/csd/shaders/decoration.frag",
    };
    for (shaders) |path| {
        const glslc = b.addSystemCommand(&.{ "glslc", "--target-env=vulkan1.4", "-I" });
        glslc.addDirectoryArg(b.path("shaders"));
        glslc.addFileInput(b.path("shaders/output.glsl"));
        glslc.addFileInput(b.path("shaders/video_common.glsl"));
        glslc.addFileArg(b.path(path));
        glslc.addArg("-o");
        const name = std.fs.path.basename(path);
        const spv = glslc.addOutputFileArg(b.fmt("{s}.spv", .{name}));
        for ([_]*std.Build.Module{ exe_mod, eval_mod }) |m| m.addAnonymousImport(b.fmt("{s}.spv", .{name}), .{ .root_source_file = spv });
    }

    const exe = b.addExecutable(.{ .name = "codotaka", .root_module = exe_mod });
    b.installArtifact(exe);
    b.installArtifact(b.addExecutable(.{ .name = "codotaka-eval", .root_module = eval_mod }));

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();
    b.step("run", "Run the demo").dependOn(&run_cmd.step);

    const test_step = b.step("test", "Run library unit tests");
    for ([_]*std.Build.Module{ geom, slot_map, drm_sync, dmabuf_feedback, scene }) |m| {
        test_step.dependOn(&b.addRunArtifact(b.addTest(.{ .root_module = m })).step);
    }
}
