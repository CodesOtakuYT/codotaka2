const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    // C bindings
    const translate = b.addTranslateC(.{
        .root_source_file = b.path("src/c.h"),
        .target = target,
        .optimize = optimize,
    });
    translate.linkSystemLibrary("libdrm", .{});

    // Wayland protocols via wayland-scanner
    const protocols = [_][]const u8{
        "xdg-shell",                  "xdg-decoration-unstable-v1",
        "linux-dmabuf-v1",            "linux-drm-syncobj-v1",
        "viewporter",                 "fractional-scale-v1",
        "presentation-time",          "color-management-v1",
        "cursor-shape-v1",            "tablet-v2",
    };
    var protocol_sources: [protocols.len]std.Build.LazyPath = undefined;
    for (protocols, &protocol_sources) |name, *source| {
        const xml = b.path(b.fmt("protocols/{s}.xml", .{name}));
        const scan_h = b.addSystemCommand(&.{ "wayland-scanner", "client-header" });
        scan_h.addFileArg(xml);
        const header = scan_h.addOutputFileArg(b.fmt("{s}-client-protocol.h", .{name}));
        translate.addIncludePath(header.dirname());

        const scan_c = b.addSystemCommand(&.{ "wayland-scanner", "private-code" });
        scan_c.addFileArg(xml);
        source.* = scan_c.addOutputFileArg(b.fmt("{s}-protocol.c", .{name}));
    }
    const c_mod = translate.createModule();

    // Vulkan bindings generated by vulkan-zig from the Khronos registry
    const vulkan = b.dependency("vulkan", .{
        .registry = b.dependency("vulkan_headers", .{}).path("registry/vk.xml"),
    }).module("vulkan-zig");

    const exe_mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "c", .module = c_mod },
            .{ .name = "vulkan", .module = vulkan },
        },
    });
    for (protocol_sources) |source| exe_mod.addCSourceFile(.{ .file = source });
    exe_mod.linkSystemLibrary("wayland-client", .{});
    exe_mod.linkSystemLibrary("libdrm", .{});
    exe_mod.linkSystemLibrary("vulkan", .{});

    // Shaders
    for ([_][]const u8{ "triangle.vert", "triangle.frag", "decoration.vert", "decoration.frag" }) |shader| {
        const glslc = b.addSystemCommand(&.{"glslc"});
        glslc.addFileArg(b.path(b.fmt("shaders/{s}", .{shader})));
        glslc.addFileInput(b.path("shaders/font8x8.glsl"));
        glslc.addArg("-o");
        const spv = glslc.addOutputFileArg(b.fmt("{s}.spv", .{shader}));
        exe_mod.addAnonymousImport(b.fmt("{s}.spv", .{shader}), .{ .root_source_file = spv });
    }

    const exe = b.addExecutable(.{ .name = "codotaka", .root_module = exe_mod });
    b.installArtifact(exe);

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();
    b.step("run", "Run the app").dependOn(&run_cmd.step);
}
